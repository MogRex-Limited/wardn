const testPolicy = `scopes:
  organisation: {}
  branch: { parent: organisation }
permissions:
  customer:view: View customers
  loan:approve_own: Approve a loan you created
roles:
  org_admin:
    description: Runs one organisation
    allow: ["*"]
  teller: [customer:view]
`

func writePolicy(t *testing.T, content string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "wardn.yaml")
	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
	return path
}

func runCLI(args ...string) (code int, stdout, stderr string) {
	var out, errOut bytes.Buffer
	code = run(args, &out, &errOut)
	return code, out.String(), errOut.String()
}

func TestCheck(t *testing.T) {
	code, out, _ := runCLI("check", "-f", writePolicy(t, testPolicy))
	if code != exitOK || !strings.Contains(out, "is valid") || !strings.Contains(out, "organisation › branch") || !strings.Contains(out, "org_admin, teller") {
		t.Fatalf("code %d, output:\n%s", code, out)
	}

	bad := writePolicy(t, "permissions:\n  loan:view: View\nroles:\n  teller: [loan:veiw]\n")
	code, _, errOut := runCLI("check", "-f", bad)
	if code != exitFailed || !strings.Contains(errOut, `did you mean "loan:view"?`) || !strings.Contains(errOut, ":4:") {
		t.Fatalf("invalid policy: code %d, stderr %q", code, errOut)
	}

	if code, _, _ := runCLI("check", "-f", filepath.Join(t.TempDir(), "missing.yaml")); code != exitFailed {
		t.Errorf("missing file: code %d", code)
	}
	if code, _, _ := runCLI("check", "-nope"); code != exitUsage {
		t.Errorf("bad flag: code %d", code)
	}
	code, out, _ = runCLI("check", "-f", writePolicy(t, "permissions:\n  a:b: X\nroles:\n  r: [a:b]\n"))
	if code != exitOK || !strings.Contains(out, "none (global only)") {
		t.Errorf("no scopes: %d %s", code, out)
	}
}

func TestGen(t *testing.T) {
	policy := writePolicy(t, testPolicy)
	out := filepath.Join(t.TempDir(), "authz", "names.go")

	if code, _, errOut := runCLI("gen", "-f", policy, "-o", out, "-check"); code != exitFailed || !strings.Contains(errOut, "out of date") {
		t.Fatalf("-check before generating: code %d, %s", code, errOut)
	}
	if code, stdout, errOut := runCLI("gen", "-f", policy, "-o", out); code != exitOK || !strings.Contains(stdout, "wrote") {
		t.Fatalf("gen: code %d, %s%s", code, stdout, errOut)
	}
	src, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"package authz", // default package: the directory name
		`LoanApproveOwn = "loan:approve_own"`,
		"RoleOrgAdmin = \"org_admin\"",
		"WardnRolesManage = wardn.PermRolesManage",
		`func ScopeBranch(id string) wardn.Scope { return wardn.NewScope("branch", id) }`,
		"// Code generated by \"wardn gen\"",
		"DO NOT EDIT.",
	} {
		if !bytes.Contains(src, []byte(want)) {
			t.Errorf("generated code is missing %q:\n%s", want, src)
		}
	}
	if code, _, _ := runCLI("gen", "-f", policy, "-o", out, "-check"); code != exitOK {
		t.Errorf("-check after generating: code %d", code)
	}
	// Changing the policy makes the generated file stale.
	if err := os.WriteFile(policy, []byte(strings.Replace(testPolicy, "teller:", "clerk:", 1)), 0o600); err != nil {
		t.Fatal(err)
	}
	if code, _, _ := runCLI("gen", "-f", policy, "-o", out, "-check"); code != exitFailed {
		t.Errorf("-check after policy change: code %d", code)
	}

	if code, _, errOut := runCLI("gen", "-f", policy, "-o", out, "-pkg", "Bad-Name"); code != exitFailed || !strings.Contains(errOut, "invalid package name") {
		t.Errorf("bad package: %d %s", code, errOut)
	}
	if code, _, _ := runCLI("gen", "-f", writePolicy(t, "roles: {}\n"), "-o", out); code != exitFailed {
		t.Errorf("invalid policy: code %d", code)
	}
	if code, _, _ := runCLI("gen", "-x"); code != exitUsage {
		t.Errorf("bad flag: code %d", code)
	}
}

func TestGenNameCollision(t *testing.T) {
	// "loan:approve" and "loan_approve:x"... both camel-case cleanly; these two
	// collide: permission "role:teller" and role "teller" are fine, but
	// permissions "a_b:c" and "a:b_c" both become ABC.
	p := writePolicy(t, "permissions:\n  a_b:c: X\n  a:b_c: Y\nroles:\n  r: [a_b:c]\n")
	code, _, errOut := runCLI("gen", "-f", p, "-o", filepath.Join(t.TempDir(), "perm", "perm.go"))
	if code != exitFailed || !strings.Contains(errOut, "both become the Go name ABC") {
		t.Fatalf("code %d, stderr %q", code, errOut)
	}
}

// TestGenCannotInjectCode: nothing in a policy file can escape into code.
func TestGenCannotInjectCode(t *testing.T) {
	// Descriptions cannot contain line breaks: the policy rejects them.
	p := writePolicy(t, "permissions:\n  a:b: \"x\\n}\\nfunc init() { panic(1) }\"\nroles:\n  r: [a:b]\n")
	if code, _, _ := runCLI("gen", "-f", p, "-o", filepath.Join(t.TempDir(), "perm", "perm.go")); code != exitFailed {
		t.Fatal("description with a newline was accepted")
	}
	// Comment-breaking text that is allowed stays inside the comment.
	policy := &wardn.Policy{
		Permissions: map[string]string{"a:b": "ends */ and `backticks` and \"quotes\""},
		Roles:       map[string]wardn.Role{"r": {Allow: []string{"a:b"}, Description: "Unicode line\u2028separator"}},
	}
	if err := policy.Validate(); err != nil {
		t.Fatal(err)
	}
	src, err := generate(policy, "evil\nfunc init() { panic(1) }.yaml", "perm")
	if err != nil {
		t.Fatal(err)
	}
	f, err := parser.ParseFile(token.NewFileSet(), "perm.go", src, 0)
	if err != nil {
		t.Fatalf("generated code does not parse: %v\n%s", err, src)
	}
	// The only functions are the generated scope constructors; there are none
	// here, because the policy declares no scopes.
	for _, d := range f.Decls {
		if fd, ok := d.(*ast.FuncDecl); ok {
			t.Fatalf("unexpected function %s in generated code:\n%s", fd.Name.Name, src)
		}
	}
	if !bytes.Contains(src, []byte("// Code generated by \"wardn gen\" from evil func init() { panic(1) }.yaml. DO NOT EDIT.")) {
		t.Fatalf("source path was not kept on one comment line:\n%s", src)
	}
}

// TestGeneratedCodeCompiles builds the generated package in a real module.
func TestGeneratedCodeCompiles(t *testing.T) {
	if testing.Short() {
		t.Skip("builds a module; skipped with -short")
	}
	goBin, err := exec.LookPath("go")
	if err != nil {
		t.Skip("go command not found")
	}
	repo, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	write := func(name, content string) {
		t.Helper()
		if err := os.MkdirAll(filepath.Dir(filepath.Join(dir, name)), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	sum, err := os.ReadFile(filepath.Join(repo, "go.sum"))
	if err != nil {
		t.Fatal(err)
	}
	write("go.mod", "module gentest\n\ngo 1.26.0\n\nrequire github.com/MogRex-Limited/wardn v0.0.0\n\nreplace github.com/MogRex-Limited/wardn => "+repo+"\n")
	write("go.sum", string(sum))
	write("wardn.yaml", testPolicy)
	write("main.go", `package main

import (
	"fmt"

	"gentest/perm"
)

func main() {
	fmt.Println(perm.CustomerView, perm.LoanApproveOwn, perm.RoleTeller, perm.WardnRolesAssign, perm.ScopeBranch("b7"))
}
`)
	if code, _, errOut := runCLI("gen", "-f", filepath.Join(dir, "wardn.yaml"), "-o", filepath.Join(dir, "perm", "perm.go")); code != exitOK {
		t.Fatalf("gen: %s", errOut)
	}
	cmd := exec.CommandContext(t.Context(), goBin, "run", ".")
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GOFLAGS=-mod=mod", "GOTOOLCHAIN=local")
	output, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("generated code does not build: %v\n%s", err, output)
	}
	if want := "customer:view loan:approve_own teller wardn:roles.assign branch:b7"; strings.TrimSpace(string(output)) != want {
		t.Fatalf("output %q, want %q", output, want)
	}
}

func TestVersionAndUsage(t *testing.T) {
	if code, out, _ := runCLI("version"); code != exitOK || !strings.HasPrefix(out, "wardn ") {
		t.Errorf("version: %d %q", code, out)
	}
	if code, out, _ := runCLI("help"); code != exitOK || !strings.Contains(out, "Usage:") {
		t.Errorf("help: %d", code)
	}
	if code, _, errOut := runCLI(); code != exitUsage || !strings.Contains(errOut, "Usage:") {
		t.Errorf("no args: %d", code)
	}
	if code, _, errOut := runCLI("frobnicate"); code != exitUsage || !strings.Contains(errOut, "unknown command") {
		t.Errorf("unknown command: %d", code)
	}
}

func TestCamel(t *testing.T) {
	for in, want := range map[string]string{
		"loan:approve":       "LoanApprove",
		"loan:approve_own":   "LoanApproveOwn",
		"wardn:roles.manage": "WardnRolesManage",
		"org_admin":          "OrgAdmin",
		"a2:b":               "A2B",
	} {
		if got := camel(in); got != want {
			t.Errorf("camel(%q) = %q, want %q", in, got, want)
		}
	}
}

// failWriter fails every write, like a closed pipe.
type failWriter struct{}

func (failWriter) Write([]byte) (int, error) { return 0, os.ErrClosed }

func TestOutputFailureIsAnError(t *testing.T) {
	if code := run([]string{"version"}, failWriter{}, &bytes.Buffer{}); code != exitFailed {
		t.Fatalf("write failure: code %d, want %d", code, exitFailed)
	}
}
