package main

import (
	"bytes"
	"fmt"
	"go/format"
	"maps"
	"slices"
	"strconv"
	"strings"

	"github.com/MogRex-Limited/wardn"
)

// generate returns Go source declaring the policy's names as constants.
//
// Everything written into the code is either an identifier built only from
// the characters policy names allow ([a-z0-9_.:]) or a value quoted with
// strconv.Quote, and descriptions (in comments) cannot contain newlines
// because the policy forbids control characters. A policy file therefore
// cannot inject code.
func generate(p *wardn.Policy, source, pkg string) ([]byte, error) {
	if !validPackageName(pkg) {
		return nil, fmt.Errorf("invalid package name %q: use lowercase letters and digits, starting with a letter", pkg)
	}
	used := map[string]string{} // identifier -> what it names
	ident := func(id, what string) (string, error) {
		if prev, ok := used[id]; ok {
			return "", fmt.Errorf("%s and %s both become the Go name %s; rename one of them", prev, what, id)
		}
		used[id] = what
		return id, nil
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by \"wardn gen\" from %s. DO NOT EDIT.\n\n", oneLine(source))
	fmt.Fprintf(&b, "// Package %s holds the permission, role and scope names from %s as Go\n// identifiers, so a typo is a compile error instead of a denied request.\npackage %s\n\n", pkg, oneLine(source), pkg)
	b.WriteString("import \"github.com/MogRex-Limited/wardn\"\n\n")

	b.WriteString("// Permissions.\nconst (\n")
	for _, name := range slices.Sorted(maps.Keys(p.Permissions)) {
		id, err := ident(camel(name), fmt.Sprintf("permission %q", name))
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "\t// %s: %s\n\t%s = %s\n", id, sanitizeComment(p.Permissions[name]), id, strconv.Quote(name))
	}
	for _, builtin := range []struct{ name, constant, desc string }{
		{wardn.PermRolesAssign, "PermRolesAssign", "Assign and revoke roles"},
		{wardn.PermRolesManage, "PermRolesManage", "Create, edit and delete custom roles"},
	} {
		id, err := ident(camel(builtin.name), fmt.Sprintf("built-in permission %q", builtin.name))
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "\t// %s: %s (built in).\n\t%s = wardn.%s\n", id, builtin.desc, id, builtin.constant)
	}
	b.WriteString(")\n\n")

	if len(p.Roles) > 0 {
		b.WriteString("// System roles.\nconst (\n")
		for _, name := range slices.Sorted(maps.Keys(p.Roles)) {
			id, err := ident("Role"+camel(name), fmt.Sprintf("role %q", name))
			if err != nil {
				return nil, err
			}
			if desc := p.Roles[name].Description; desc != "" {
				fmt.Fprintf(&b, "\t// %s: %s\n", id, sanitizeComment(desc))
			}
			fmt.Fprintf(&b, "\t%s = %s\n", id, strconv.Quote(name))
		}
		b.WriteString(")\n")
	}

	for _, name := range slices.Sorted(maps.Keys(p.Scopes)) {
		id, err := ident("Scope"+camel(name), fmt.Sprintf("scope type %q", name))
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "\n// %s returns the %s scope with the given ID.\nfunc %s(id string) wardn.Scope { return wardn.NewScope(%s, id) }\n",
			id, name, id, strconv.Quote(name))
	}

	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("internal error formatting generated code: %w", err)
	}
	return src, nil
}

// camel turns a policy name into an exported Go identifier:
// "loan:approve_own" → "LoanApproveOwn", "wardn:roles.manage" → "WardnRolesManage".
func camel(name string) string {
	var b strings.Builder
	for _, part := range strings.FieldsFunc(name, func(r rune) bool { return r == ':' || r == '.' || r == '_' }) {
		b.WriteString(strings.ToUpper(part[:1]))
		b.WriteString(part[1:])
	}
	return b.String()
}

// oneLine replaces line breaks, so text cannot escape a // comment.
func oneLine(s string) string {
	return strings.Map(func(r rune) rune {
		if r == '\n' || r == '\r' || r == '\u2028' || r == '\u2029' {
			return ' '
		}
		return r
	}, s)
}

// sanitizeComment makes a description safe and tidy inside a // comment.
func sanitizeComment(s string) string {
	s = oneLine(s)
	if !strings.HasSuffix(s, ".") {
		s += "."
	}
	return s
}

func validPackageName(pkg string) bool {
	if pkg == "" || pkg[0] < 'a' || pkg[0] > 'z' {
		return false
	}
	for i := 0; i < len(pkg); i++ {
		if c := pkg[i]; (c < 'a' || c > 'z') && (c < '0' || c > '9') {
			return false
		}
	}
	return true
}
